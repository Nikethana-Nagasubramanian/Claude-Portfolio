// Build a separate static review tree from the published portfolio sources.
// Existing public HTML, scripts, styles, assets, and Vercel routes stay untouched.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'dive');
const marker = 'Generated by tools/build-dive.mjs';
const widget = '<script src="https://inflight.co/widget.js" data-org="aius9qpt" data-path="/dive" async></script>';
// Refuse to replace an independently authored /dive route.
if (existsSync(join(root, 'dive.html')) || (existsSync(output) &&
    !readFileSync(join(output, 'index.html'), 'utf8').includes(marker))) {
  throw new Error('An existing /dive route must not be overwritten.');
}
const config = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));
if (config.rewrites?.some(item => item.source === '/dive' || item.source.startsWith('/dive/'))) {
  throw new Error('An existing /dive rewrite must not be overwritten.');
}
const rewrites = new Map(config.rewrites.filter(item => !item.has).map(item => [item.source, item.destination]));
const shared = new Set(['site-rail.js', 'site-router.js', 'rail-ui.js', 'background-explorer.js']);
const pages = new Map();
const aliases = new Map();

function sourceFor(pathname) {
  let file = pathname === '/' ? '/index.html' : (rewrites.get(pathname) || pathname);
  for (const candidate of [file, file + '.html', file + '/index.html']) {
    if (candidate.endsWith('.html') && existsSync(join(root, candidate))) return candidate.slice(1);
  }
}
function reviewPath(source) {
  if (source === 'index.html') return '/dive';
  return '/dive/' + source.replace(/\/dist\/index\.html$/, '').replace(/\.html$/, '');
}
function discover(pathname) {
  const source = sourceFor(pathname);
  if (!source) return;
  aliases.set(pathname, reviewPath(source));
  aliases.set('/' + source, reviewPath(source));
  aliases.set('/' + source.replace(/\.html$/, ''), reviewPath(source));
  if (pages.has(source)) return;
  const html = readFileSync(join(root, source), 'utf8');
  pages.set(source, html);
  for (const match of html.matchAll(/<a\b[^>]*\bhref\s*=\s*(["'])(.*?)\1/gi)) {
    const href = match[2];
    if (!href || /^(?:#|[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) continue;
    discover(new URL(href, 'https://portfolio.invalid/' + source).pathname);
  }
}
// The shell's four navigation links are rendered by site-rail.js.
for (const page of ['/', '/about', '/playground', '/archive']) discover(page);
for (const [alias, destination] of rewrites) {
  const source = sourceFor(alias);
  if (source && pages.has(source)) aliases.set(alias, reviewPath(source));
}

function urlFor(value, source, attribute) {
  if (!value || /^(?:#|[a-z][a-z\d+.-]*:|\/\/)/i.test(value)) return value;
  const url = new URL(value.replaceAll('&amp;', '&'), 'https://portfolio.invalid/' + source);
  if (attribute === 'href' && aliases.has(url.pathname)) return aliases.get(url.pathname) + url.search + url.hash;
  if (attribute === 'src' && shared.has(url.pathname.slice(1))) {
    return '/dive/_shared' + url.pathname + url.search;
  }
  return url.pathname + url.search + url.hash;
}
function save(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
for (const [source, html] of pages) {
  let result = html.replace(/\b(href|src|poster|action)\s*=\s*(["'])(.*?)\2/gi,
    (_, attribute, quote, value) => attribute + '=' + quote + urlFor(value, source, attribute.toLowerCase()) + quote);
  result = result.replace(/<head>/i, `<head>\n  <!-- ${marker}. -->\n  <meta name="robots" content="noindex, nofollow" />\n  ${widget}\n  <script defer src="/dive/_shared/review-links.js"></script>`);
  const destination = reviewPath(source) === '/dive' ? 'index.html' : reviewPath(source).slice('/dive/'.length) + '.html';
  save(join(output, destination), result);
}
for (const file of shared) {
  let script = readFileSync(join(root, file), 'utf8');
  // Dynamic portrait, icon, and explorer assets retain their public asset URLs.
  script = script.replace(/(?<![\w/])assets\//g, '/assets/');
  if (file === 'site-rail.js') {
    script = script.replace(/href: "(index|about|playground|archive)\.html"/g,
      (_, name) => `href: "${name === 'index' ? '/dive' : '/dive/' + name}"`);
    script = script.replace('link.href.replace(/\\.html$/, "") === page',
      '(link.href === "/dive" ? "index" : link.href.split("/").pop()) === page');
    script = script.replace('location.pathname.split("/").pop()', 'location.pathname.replace(/^\\/dive\\/?$/, "").split("/").pop()');
  }
  if (file === 'site-router.js') {
    script = script.replace("if (url.origin !== location.origin) return null;",
      "if (url.origin !== location.origin || !/^\\/dive(?:\\/|$)/.test(url.pathname)) return null;");
    script = script.replace("url.pathname.replace(/^\\//, '')", "url.pathname.replace(/^\\/dive\\/?/, '')");
    script = script.replace("fetch('/' + key + '.html'", "fetch('/dive/' + key + '.html'");
  }
  save(join(output, '_shared', file), `// ${marker}.\n` + script);
}
// Keep links created by existing tool bundles in the review tree too. This also
// covers modified clicks and context-menu navigation without replacing assets.
save(join(output, '_shared/review-links.js'), `// ${marker}.
(() => {
  const routes = ${JSON.stringify(Object.fromEntries(aliases), null, 2)};
  function scope(link) {
    const value = link.getAttribute('href');
    if (!value || /^(?:#|[a-z][a-z\\d+.-]*:|\\/\\/)/i.test(value)) return;
    const url = new URL(value, location.href);
    if (routes[url.pathname]) link.setAttribute('href', routes[url.pathname] + url.search + url.hash);
  }
  function update(node) {
    if (node.nodeType !== 1) return;
    if (node.matches('a[href]')) scope(node);
    node.querySelectorAll('a[href]').forEach(scope);
  }
  update(document.documentElement);
  new MutationObserver(records => records.forEach(record => {
    if (record.type === 'attributes') scope(record.target);
    else record.addedNodes.forEach(update);
  })).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ['href'] });
})();
`);
save(join(output, 'manifest.json'), JSON.stringify({ generator: marker, pages: [...pages.keys()] }, null, 2) + '\n');
console.log(`Generated ${pages.size} review pages in /dive; public sources unchanged.`);
